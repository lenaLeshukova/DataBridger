import json
import pytest
from src.services import analyze_cashback_categories


def test_analyze_cashback_categories_basic():
    """
        Тестирует базовый расчет кешбэка по категориям за конкретный месяц.
        Проверяет фильтрацию по дате (месяц/год) и корректность суммирования 1% от транзакций.
        """
    # Тестовые данные, имитирующие ваш Excel
    data = [
        {"Дата операции": "31.12.2021 16:44:00", "Категория": "Супермаркеты", "Сумма операции": -10000},
        {"Дата операции": "01.12.2021 10:00:00", "Категория": "Супермаркеты", "Сумма операции": -5000},
        {"Дата операции": "01.01.2022 00:00:00", "Категория": "Фастфуд", "Сумма операции": -1000},  # Другой год
    ]

    # Ожидаем: (10000 + 5000) * 0.01 = 150 кешбэка для Супермаркетов
    result_json = analyze_cashback_categories(data, 2021, 12)
    result = json.loads(result_json)

    assert result["Супермаркеты"] == 150
    assert "Фастфуд" not in result  # Январь не должен попасть


def test_analyze_cashback_empty_data():
    """Проверяет поведение функции при передаче пустого списка транзакций."""
    assert analyze_cashback_categories([], 2021, 12) == "{}"
